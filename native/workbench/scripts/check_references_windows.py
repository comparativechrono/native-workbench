        # Queue ordinary keyboard input so notifications run on the UI thread.
        require(user.PostMessageW(hwnd, 0x0100, value, 1)
                and user.PostMessageW(hwnd, 0x0101, value, 0xC0000001),
                "Could not queue native keyboard input.")

